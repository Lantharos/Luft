pub fn translated(key: &str) -> Option<String> {
    if let Some(number) = workspace(key, "move-to-workspace-") {
        return Some(t!(
            L10N,
            "desktop-shortcut-move-to-workspace",
            number = number
        ));
    }
    if let Some(number) =
        workspace(key, "switch-to-workspace-").or_else(|| workspace(key, "workspace-"))
    {
        return Some(t!(
            L10N,
            "desktop-shortcut-switch-to-workspace",
            number = number
        ));
    }
    message(key).map(|id| t!(L10N, id))
}
