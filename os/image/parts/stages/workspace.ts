import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

type Package = { name: string; version: string; source?: string; dependencies: string[]; text: string };
type Manifest = Record<string, Record<string, unknown> | undefined> & { target?: Record<string, Record<string, unknown>> };

const DEPENDENCY_KINDS = ['dependencies', 'dev-dependencies', 'build-dependencies'];
const LOCK_HEADER = '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n';

function listed(manifest: string, key: string) {
  const list = new RegExp(`^${key} = \\[([^\\]]*)\\]`, 'm').exec(manifest);
  return list ? [...list[1].matchAll(/"([^"]+)"/g)].map((match) => match[1]) : [];
}

function relist(manifest: string, key: string, kept: string[]) {
  const entries = kept.map((entry) => `    "${entry}",\n`).join('');
  return manifest.replace(new RegExp(`^${key} = \\[[^\\]]*\\]`, 'm'), `${key} = [\n${entries}]`);
}

function inheritedDependencies(manifest: Manifest) {
  const scopes = [manifest, ...Object.values(manifest.target ?? {})] as Record<string, unknown>[];
  return scopes.flatMap((scope) => DEPENDENCY_KINDS.flatMap((kind) => Object.keys((scope[kind] as object | undefined) ?? {})));
}

function keepDependencies(manifest: string, used: Set<string>) {
  let inSection = false;
  return manifest
    .split('\n')
    .filter((line) => {
      if (line.startsWith('[')) inSection = line === '[workspace.dependencies]';
      const name = /^([\w-]+) = /.exec(line)?.[1];
      return !inSection || !name || used.has(name);
    })
    .join('\n')
    .replace(/\[workspace\.dependencies\]\n\n+/, '[workspace.dependencies]\n')
    .replace(/\n\n\n+/g, '\n\n');
}

function parseLock(lock: string): Package[] {
  return lock
    .split('\n[[package]]\n')
    .slice(1)
    .map((text) => {
      const field = (key: string) => new RegExp(`^${key} = "([^"]*)"`, 'm').exec(text)?.[1];
      const dependencies = /^dependencies = \[\n([^\]]*)\]/m.exec(text)?.[1] ?? '';
      return {
        name: field('name')!,
        version: field('version')!,
        source: field('source')?.replace(/#.*$/, ''),
        dependencies: [...dependencies.matchAll(/"([^"]+)"/g)].map((match) => match[1]),
        text,
      };
    });
}

function resolver(packages: Package[]) {
  return (reference: string) => {
    const [, name, version, source] = /^(\S+)(?: (\S+))?(?: \((.+)\))?$/.exec(reference)!;
    return packages.find(
      (candidate) => candidate.name === name && (!version || candidate.version === version) && (!source || candidate.source === source),
    )!;
  };
}

function reference(target: Package, packages: Package[]) {
  const named = packages.filter((candidate) => candidate.name === target.name);
  if (named.length === 1) return target.name;
  const versioned = named.filter((candidate) => candidate.version === target.version);
  return versioned.length === 1 ? `${target.name} ${target.version}` : `${target.name} ${target.version} (${target.source})`;
}

function closure(packages: Package[], roots: string[]) {
  const resolve = resolver(packages);
  const kept = new Set<Package>();
  const visit = (pkg: Package) => {
    if (kept.has(pkg)) return;
    kept.add(pkg);
    pkg.dependencies.map(resolve).forEach(visit);
  };
  for (const name of roots) packages.filter((pkg) => pkg.name === name && !pkg.source).forEach(visit);
  return kept;
}

export function lockedPackages(lock: string, roots: string[]) {
  return new Set([...closure(parseLock(lock), roots)].map((pkg) => `${pkg.name} ${pkg.version} ${pkg.source ?? ''}`));
}

function pruneLock(lock: string, roots: string[]) {
  const packages = parseLock(lock);
  const resolve = resolver(packages);
  const kept = closure(packages, roots);
  const remaining = packages.filter((pkg) => kept.has(pkg));
  const blocks = remaining.map((pkg) => {
    if (pkg.dependencies.length === 0) return pkg.text;
    const dependencies = pkg.dependencies.map((dependency) => ` "${reference(resolve(dependency), remaining)}",\n`).join('');
    return pkg.text.replace(/^dependencies = \[\n[^\]]*\]/m, `dependencies = [\n${dependencies}]`);
  });
  return `${LOCK_HEADER}${blocks.map((block) => `\n[[package]]\n${block}`).join('')}`;
}

function pathDependencies(manifest: string) {
  const dependencies = (Bun.TOML.parse(manifest) as { workspace?: { dependencies?: Record<string, unknown> } }).workspace?.dependencies ?? {};
  return new Map(
    Object.entries(dependencies).flatMap(([name, spec]) => {
      const path = (spec as { path?: unknown } | undefined)?.path;
      return typeof path === 'string' ? [[name, path] as const] : [];
    }),
  );
}

export function prunedWorkspace(manifest: string, lock: string, memberManifest: (dir: string) => string | undefined) {
  const paths = pathDependencies(manifest);
  const present = (name: string) => !paths.has(name) || memberManifest(paths.get(name)!) !== undefined;
  const members = listed(manifest, 'members').flatMap((dir) => {
    const text = memberManifest(dir);
    const parsed = text ? (Bun.TOML.parse(text) as Manifest) : undefined;
    return parsed && inheritedDependencies(parsed).every(present) ? [{ dir, manifest: parsed }] : [];
  });
  const dirs = members.map((member) => member.dir);
  const used = new Set(members.flatMap((member) => inheritedDependencies(member.manifest)));
  const defaults = listed(manifest, 'default-members').filter((dir) => dirs.includes(dir));
  const pruned = keepDependencies(relist(relist(manifest, 'members', dirs), 'default-members', defaults), used);
  const names = members.map((member) => String(member.manifest.package!.name));
  return { manifest: pruned, lock: pruneLock(lock, names) };
}

if (import.meta.main) {
  const [root] = process.argv.slice(2);
  if (!root) throw new Error('Usage: workspace.ts ROOT');
  const read = (path: string) => readFileSync(join(root, path), 'utf8');
  const memberManifest = (dir: string) => (existsSync(join(root, dir, 'Cargo.toml')) ? read(join(dir, 'Cargo.toml')) : undefined);
  const workspace = prunedWorkspace(read('Cargo.toml'), read('Cargo.lock'), memberManifest);
  writeFileSync(join(root, 'Cargo.toml'), workspace.manifest);
  writeFileSync(join(root, 'Cargo.lock'), workspace.lock);
  const fetch = Bun.spawnSync(['cargo', 'fetch', '--manifest-path', join(root, 'Cargo.toml')], { stdio: ['ignore', 'inherit', 'inherit'] });
  if (!fetch.success) process.exit(fetch.exitCode ?? 1);
}
