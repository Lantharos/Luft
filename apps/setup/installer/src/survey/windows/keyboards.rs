pub(super) fn xkb(klid: &str) -> Option<Keyboard> {
    let klid = u32::from_str_radix(klid.trim(), 16).ok()?;
    let index = LAYOUTS.binary_search_by_key(&klid, |(id, ..)| *id).ok()?;
    let (_, layout, variant) = LAYOUTS[index];
    Some(Keyboard {
        layout: layout.into(),
        variant: variant.into(),
    })
}
