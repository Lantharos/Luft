//! Minimal 8x8 bitmap font for the SUSHI fallback logo.

const GLYPH_W: usize = 8;
const GLYPH_H: usize = 8;

pub fn draw_text_scaled(
    put_pixel: &mut dyn FnMut(usize, usize, u8, u8, u8),
    x: usize,
    y: usize,
    w: usize,
    h: usize,
    text: &str,
    scale: usize,
    color: (u8, u8, u8),
) {
    let scale = scale.max(1);
    let spacing = 1;
    let text_w = text.len() * (GLYPH_W + spacing) * scale;
    let text_h = GLYPH_H * scale;
    let start_x = x + w.saturating_sub(text_w) / 2;
    let start_y = y + h.saturating_sub(text_h) / 2;

    let mut cursor_x = start_x;
    for ch in text.chars() {
        draw_glyph_scaled(put_pixel, cursor_x, start_y, ch, scale, color);
        cursor_x += (GLYPH_W + spacing) * scale;
    }
}

pub fn text_pixel_width(text: &str, scale: usize) -> usize {
    let spacing = 1;
    let scale = scale.max(1);
    if text.is_empty() {
        return 0;
    }
    text.len() * (GLYPH_W + spacing) * scale - spacing * scale
}

/// Left-aligned single-line text, horizontally centered on screen.
pub fn draw_text_line(
    put_pixel: &mut dyn FnMut(usize, usize, u8, u8, u8),
    _x: usize,
    y: usize,
    screen_w: usize,
    scale: usize,
    text: &str,
    color: (u8, u8, u8),
) {
    let scale = scale.max(1);
    let text_w = text_pixel_width(text, scale);
    let start_x = screen_w.saturating_sub(text_w) / 2;
    let mut cursor_x = start_x;
    for ch in text.chars() {
        draw_glyph_scaled(put_pixel, cursor_x, y, ch, scale, color);
        cursor_x += (GLYPH_W + 1) * scale;
    }
}

pub fn fit_scale(text: &str, w: usize, h: usize) -> usize {
    let spacing = 1;
    let text_w = text.len() * (GLYPH_W + spacing) - spacing;
    if text_w == 0 || GLYPH_H == 0 {
        return 1;
    }
    let scale_w = w / text_w;
    let scale_h = h / GLYPH_H;
    scale_w.max(1).min(scale_h.max(1)).max(1)
}

fn draw_glyph_scaled(
    put_pixel: &mut dyn FnMut(usize, usize, u8, u8, u8),
    x: usize,
    y: usize,
    ch: char,
    scale: usize,
    color: (u8, u8, u8),
) {
    let glyph = glyph_bits(ch);
    for row in 0..GLYPH_H {
        let bits = glyph[row];
        for col in 0..GLYPH_W {
            if (bits >> (7 - col)) & 1 == 0 {
                continue;
            }
            for sy in 0..scale {
                for sx in 0..scale {
                    put_pixel(
                        x + col * scale + sx,
                        y + row * scale + sy,
                        color.0,
                        color.1,
                        color.2,
                    );
                }
            }
        }
    }
}

